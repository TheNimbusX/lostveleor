namespace Game.Sim
{
    /// <summary>
    /// Уникальный артефакт на время забега (владелец, 24 сентября): геймченджер, меняющий
    /// правило, а не цифру. Слот один; с босса всегда выбор 1 из 3, из тайника — очень редко.
    /// Замена — только выбором игрока, забег кончился — артефакт пропал.
    ///
    /// Набор акта I — список владельца (ui/unique-artifacts.md.md), утверждён той же ночью.
    /// Активные включаются клавишей F и уходят на перезарядку, Обет Хранителя срабатывает сам.
    /// Номера входят в хеш и реплеи: новые — только в конец, снятые не переиспользуются.
    /// </summary>
    public enum RunArtifact : byte
    {
        None = 0,

        // 1–3 — первые пассивные артефакты (Вихревой дар, Взрывной рунический камень, Огненный
        // след), сняты 24 сентября: набор заменён списком владельца. Номера не переиспользуются.

        /// <summary>Солнечная Печать: 4 с полной неуязвимости, можно атаковать.</summary>
        SunSeal = 4,
        /// <summary>Циферблат Возврата: сброс перезарядки всех способностей и кувырка.</summary>
        ReturnDial = 5,
        /// <summary>Зеркало Возмездия: 6 с весь урон по герою возвращается атакующему, герою −25%.</summary>
        VengeanceMirror = 6,
        /// <summary>Сердце Вечной Зимы: враги в 8 м замерзают на 5 с, босс и элита замедлены на 40%.</summary>
        WinterHeart = 7,
        /// <summary>Песочные Часы Безвременья: 4 с враги и снаряды стоят, урон копится и приходит разом.</summary>
        Hourglass = 8,
        /// <summary>Лик Пустоты: 6 с фазы — не бьют, сквозь врагов, атаковать нельзя; досрочный выход взрывается.</summary>
        VoidVisage = 9,
        /// <summary>Багровое Сердце: 10 с — за каждые −10% здоровья сильнее и быстрее, в конце взрыв.</summary>
        CrimsonHeart = 10,
        /// <summary>Обет Хранителя (пассивный): вместо смерти — половина здоровья, 3 с неуязвимости, волна.</summary>
        GuardianVow = 11,
    }

    public static class RunArtifacts
    {
        /// <summary>Сколько артефактов в наборе (без None и снятых).</summary>
        public const int Count = 8;

        /// <summary>Первый номер действующего набора: 1–3 сняты.</summary>
        private const int First = (int)RunArtifact.SunSeal;

        /// <summary>Шанс, что тайник вместо вещи отдаст артефакт, в процентах. Заглушка баланса.</summary>
        public const int CacheChancePercent = 3;

        public static RunArtifact At(int index) => (RunArtifact)(index + First);

        public static bool IsValid(RunArtifact artifact) => (int)artifact >= First && (int)artifact < First + Count;
    }
}
