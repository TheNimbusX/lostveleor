namespace Game.Sim
{
    /// <summary>
    /// Стабильный идентификатор: строка, свёрнутая в int по FNV-1a.
    ///
    /// ЗАЧЕМ ИМЕННО ТАК. Идентификаторы предметов и аффиксов попадают в сейвы
    /// и реплеи. Индекс массива или порядковый номер элемента enum сдвинется
    /// при первой же вставке нового аффикса в середину списка — и все сохранённые
    /// предметы всех игроков станут другими предметами. Строка «affix.fire_damage»
    /// не сдвигается никогда, а хеш от неё даёт дешёвое сравнение и компактное
    /// хранение.
    ///
    /// Хеш считается ОДИН РАЗ при загрузке данных, не в горячем пути.
    /// </summary>
    public static class StableId
    {
        private const uint Offset = 2166136261u;
        private const uint Prime = 16777619u;

        /// <summary>
        /// FNV-1a по байтам UTF-16. Порядок байтов задан явно, а не взят
        /// у платформы: иначе одна и та же строка дала бы разный id на разных
        /// машинах, и сейв перестал бы переноситься.
        /// </summary>
        public static int Of(string id)
        {
            if (id == null) return 0;

            uint hash = Offset;
            for (int i = 0; i < id.Length; i++)
            {
                char c = id[i];
                hash ^= (uint)(c & 0xFF);
                hash *= Prime;
                hash ^= (uint)((c >> 8) & 0xFF);
                hash *= Prime;
            }
            return unchecked((int)hash);
        }
    }
}
