namespace Game.Sim
{
    /// <summary>
    /// Где сейчас игрок. Хаб ровно один — лагерь; всё остальное происходит
    /// в Разломе.
    /// </summary>
    public enum GameMode : byte
    {
        Camp = 0,
        Rift = 1,

        /// <summary>
        /// Экран итогов забега. Отдельный режим, а не всплывашка над Разломом:
        /// именно здесь лагерь конкурирует с кнопкой «повторить» за внимание,
        /// и это его единственный шанс выиграть честно.
        /// </summary>
        Summary = 2,
    }

    /// <summary>
    /// Команды лагеря.
    ///
    /// Приходят тем же полем InputFrame.Command, что и команды забега, и
    /// значения у них пересекаются. Это не ошибка: поле читается ПО РЕЖИМУ,
    /// и в лагере единица означает «войти в Разлом», а в Разломе — «взять
    /// первую награду». Один байт вместо двух, и невозможно случайно послать
    /// команду не туда.
    ///
    /// Значения попадают в реплей — не переставлять.
    /// </summary>
    public enum CampCommand : byte
    {
        None = 0,

        /// <summary>Портал в Разлом. Начинает забег на новом сиде.</summary>
        EnterRift = 1,

        /// <summary>
        /// Повторить одним нажатием — прямо с экрана итогов, не заходя в лагерь.
        /// Эта кнопка ОБЯЗАНА существовать: без неё лагерь становится
        /// принудительным коридором между забегами.
        /// </summary>
        RepeatRift = 2,

        /// <summary>Вернуться в лагерь с экрана итогов.</summary>
        ReturnToCamp = 3,

        /// <summary>Автразбор по фильтру: всё непомеченное уходит в осколки.</summary>
        SalvageJunk = 4,

        /// <summary>Встать на Полигон или сойти с него.</summary>
        ToggleProvingGround = 5,
    }

    /// <summary>
    /// Три валюты с разными ритмами. Разными они и должны остаться: одна
    /// валюта на всё — это одна шкала, а решений на одной шкале не бывает.
    ///
    /// Значения попадают в сейв — не переставлять.
    /// </summary>
    public enum CurrencyType : byte
    {
        /// <summary>Поток. Ремонт, услуги, базовые вещи у торговца.</summary>
        Gold = 0,

        /// <summary>Из разбора. Топливо перековки.</summary>
        Shards = 1,

        /// <summary>Редкий, с третьего акта. Топ снаряжения и эндгейм.</summary>
        Lavidium = 2,

        /// <summary>Не валюта. Размер массива.</summary>
        Count = 3,
    }

    /// <summary>
    /// Услуги лагеря. Открываются по актам — награда за акт это новый глагол
    /// в лагере, а не строчка статов.
    ///
    /// Флаги, а не список: набор открытого — это состояние, которое ложится
    /// в сейв одним числом.
    /// </summary>
    [System.Flags]
    public enum CampService : uint
    {
        None = 0,

        /// <summary>Акт I, арват. Ремонт, улучшение баз, первая перековка.</summary>
        Smith = 1 << 0,

        /// <summary>Акт I, немор. Продажа мусора, узкий ассортимент баз.</summary>
        Trader = 1 << 1,

        /// <summary>Акт II, гелид. Летопись — каталог находок.</summary>
        Chronicler = 1 << 2,

        /// <summary>Акт II. Общий сундук на вкладках.</summary>
        Stash = 1 << 3,

        /// <summary>Акт III, цинер. Лавидий, топовое снаряжение и эндгейм.</summary>
        Founder = 1 << 4,

        /// <summary>Акт III. Вход в бесконечную часть.</summary>
        RiftPortal = 1 << 5,

        /// <summary>
        /// Полигон. Не привязан к акту: он существует ради того, чтобы понять,
        /// что делает найденная вещь, и нужен ровно с первой найденной вещи.
        /// </summary>
        ProvingGround = 1 << 6,
    }
}
