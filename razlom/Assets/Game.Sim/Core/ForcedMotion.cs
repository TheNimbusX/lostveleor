namespace Game.Sim
{
    /// <summary>
    /// Кто и зачем тащит тело. Нужен не поведению, а представлению и тестам:
    /// рывок игрока и волок врага выглядят по-разному и звучат по-разному,
    /// хотя считаются одним кодом.
    /// </summary>
    public enum ForcedMotionKind : byte
    {
        None = 0,

        /// <summary>Тело тянут к точке чужой волей. Подсечка.</summary>
        Dragged = 1,

        /// <summary>Тело само уходит в точку. Бросок якоря, Шаг по цепи.</summary>
        Lunge = 2,
    }

    /// <summary>
    /// ПРИНУДИТЕЛЬНОЕ ПЕРЕМЕЩЕНИЕ — ОДНА ПОДСИСТЕМА НА ВЕСЬ КИТ.
    ///
    /// Три способности Пелага из четырёх двигают тела, и все три сводятся к
    /// одному: за N тиков переставить сущность из текущей точки в целевую.
    /// Отличаются только тем, кого двигают и с какой скоростью.
    ///
    /// * Бросок якоря — тянет ИГРОКА к точке;
    /// * Подсечка — тянет ВРАГОВ к игроку;
    /// * Шаг по цепи — тянет игрока по цепочке точек, по одной за раз.
    ///
    /// Три правила, каждое из опыта, и ни одно не является украшением:
    ///
    /// 1. ДВИЖЕНИЕ ИДЁТ ЧЕРЕЗ ТУ ЖЕ ПРОВЕРКУ СТЕН, что и обычный шаг. В
    ///    симуляции есть стены (LayoutMap.IsWalkable) и скольжение вдоль них;
    ///    отдельный путь для тяги означал бы, что способность умеет то, чего
    ///    не умеет ходьба, — протаскивать сквозь геометрию.
    ///
    /// 2. ТЯЖЁЛЫХ НЕ ТЯНЕТ. Лист способностей говорит «обычных тянет, тяжёлых
    ///    нет», и это не пожелание: сопротивление берётся из PushWeight,
    ///    который уже есть у каждой сущности и уже участвует в расталкивании.
    ///    Одна величина на оба случая — иначе тяжёлый враг оказался бы тяжёлым
    ///    для толпы и лёгким для крюка.
    ///
    /// 3. ПРИНУДИТЕЛЬНОЕ ДВИЖЕНИЕ СИЛЬНЕЕ СОБСТВЕННОГО. Пока тело тащат, оно
    ///    не идёт своим шагом и не отменяет тягу приказом. Иначе враг,
    ///    которого волокут, продолжал бы идти к игроку и приезжал бы вдвое
    ///    быстрее, чем задумано.
    ///
    /// Состояние живёт в EntityStore рядом с позицией, потому что это
    /// состояние ТЕЛА, а не способности: способность кончилась, а тело ещё
    /// летит. И оно входит в хеш забега — иначе реплей разъедется.
    /// </summary>
    public static class ForcedMotion
    {
        /// <summary>
        /// Выше этого веса тело не тянут вовсе.
        ///
        /// Единица — обычный враг, у игрока намеренно больше. Порог в 1.5
        /// оставляет место для «тяжёлого» врага между обычным и игроком:
        /// его нельзя ни стянуть Подсечкой, ни вынести толпой.
        /// </summary>
        public static readonly Fix64 ResistThreshold = Fix64.Ratio(15, 10);

        /// <summary>Минимум тиков на любое принудительное перемещение.</summary>
        public const int MinTicks = 2;

        /// <summary>
        /// Назначает телу принудительное перемещение к точке.
        ///
        /// Возвращает false, если тело слишком тяжёлое: вызывающий по этому
        /// признаку решает, показывать ли «цель устояла».
        /// </summary>
        public static bool Begin(EntityStore entities, int id, FixVec2 target,
            int ticks, ForcedMotionKind kind)
        {
            if ((uint)id >= (uint)entities.Count) return false;
            if (!entities.Alive[id]) return false;

            // Рывок собственного тела весом не ограничен: игрок тянет сам
            // себя, и «слишком тяжёлый, чтобы прыгнуть» было бы абсурдом.
            if (kind == ForcedMotionKind.Dragged
                && entities.PushWeight[id] > ResistThreshold)
                return false;

            if (ticks < MinTicks) ticks = MinTicks;

            entities.ForcedTarget[id] = target;
            entities.ForcedTicksLeft[id] = ticks;
            entities.ForcedKind[id] = (byte)kind;
            return true;
        }

        /// <summary>Снимает тягу — смерть, новый Разлом, отмена способности.</summary>
        public static void Clear(EntityStore entities, int id)
        {
            entities.ForcedTicksLeft[id] = 0;
            entities.ForcedKind[id] = (byte)ForcedMotionKind.None;
            entities.ForcedTarget[id] = FixVec2.Zero;
        }

        /// <summary>Тащат ли тело прямо сейчас.</summary>
        public static bool IsActive(EntityStore entities, int id)
            => (uint)id < (uint)entities.Count && entities.ForcedTicksLeft[id] > 0;
    }
}
