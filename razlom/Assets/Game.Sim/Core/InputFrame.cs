using System;

namespace Game.Sim
{
    /// <summary>
    /// Состояния ввода, которые не являются числами. Новые биты добавлять
    /// только в конец: значение попадает в реплей.
    /// </summary>
    [Flags]
    public enum InputFlags : byte
    {
        None = 0,

        /// <summary>
        /// Приказ идти в точку Aim — правая кнопка мыши.
        /// Единственный способ управлять движением: направления с клавиатуры нет.
        /// </summary>
        MoveOrder = 1 << 0,

        /// <summary>
        /// Приказ бить — та же правая кнопка, пока она зажата.
        ///
        /// Атака НЕ автоматическая: персонаж, который бьёт сам по себе,
        /// отнимает у игрока единственное решение, которое у него есть в бою.
        /// Зажал — бьёт ближайшую цель в секторе перед собой; отпустил —
        /// перестал и просто идёт.
        /// </summary>
        Attack = 1 << 1,
    }

    /// <summary>
    /// Ввод одного тика. Аналоговые значения квантуются в Fix64 ЕЩЁ НА ЗАХВАТЕ,
    /// до попадания в симуляцию — иначе float с геймпада станет источником расхождения.
    /// </summary>
    [Serializable]
    public struct InputFrame
    {
        /// <summary>
        /// Точка под курсором в мировых координатах симуляции. Она же цель
        /// приказа на движение, она же направление разворота.
        ///
        /// Направления с клавиатуры в этой игре нет: игрок указывает ТОЧКУ,
        /// а как до неё дойти — забота симуляции. Это и есть управление жанра.
        /// </summary>
        public FixVec2 Aim;

        /// <summary>Биты 0..3 — нажатие способностей 1..4 в этом тике.</summary>
        public byte AbilityMask;

        /// <summary>Битовое поле InputFlags.</summary>
        public byte Flags;

        /// <summary>
        /// Кого игрок назначил целью, или -1.
        ///
        /// Индекс приходит из представления: только оно знает, на кого наведён
        /// курсор. Решает по нему всё равно симуляция — она проверяет, что цель
        /// жива и вражеская, и она же ведёт к ней персонажа.
        ///
        /// Ноль здесь означал бы «игрок», поэтому пустое значение именно -1,
        /// а не ноль: структура создаётся нулями, и молчаливый приказ бить
        /// себя — не та ошибка, которую хочется искать.
        /// </summary>
        public int AttackTarget;

        /// <summary>
        /// Команда забега: выбор награды, выход из Разлома. Значения RunCommand.
        ///
        /// Здесь, а не отдельным вызовом API: выбор награды — такое же решение
        /// игрока, как шаг или удар, и реплей обязан его воспроизводить.
        /// Команда, поданная мимо потока ввода, сделала бы забег невоспроизводимым.
        /// </summary>
        public byte Command;

        public bool Ability(int index) => (AbilityMask & (1 << index)) != 0;
        public bool Has(InputFlags flag) => (Flags & (byte)flag) != 0;

        public static InputFrame Empty => new InputFrame
        {
            Aim = FixVec2.Zero,
            AbilityMask = 0,
            Flags = 0,
            Command = 0,
            AttackTarget = -1,
        };

        /// <summary>
        /// Есть ли в кадре назначенная цель. Пустой InputFrame создаётся нулями,
        /// поэтому ноль тоже считается отсутствием цели — иначе каждый кадр,
        /// собранный по умолчанию, назначал бы целью игрока.
        /// </summary>
        public bool HasAttackTarget => AttackTarget > 0;

        public void HashInto(ref ulong hash)
        {
            Hashing.Mix(ref hash, Aim.X);
            Hashing.Mix(ref hash, Aim.Y);
            Hashing.Mix(ref hash, (int)AbilityMask);
            Hashing.Mix(ref hash, (int)Flags);
            Hashing.Mix(ref hash, (int)Command);
            Hashing.Mix(ref hash, AttackTarget);
        }
    }
}
