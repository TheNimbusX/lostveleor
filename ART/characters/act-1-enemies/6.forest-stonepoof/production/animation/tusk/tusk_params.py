BONES = ('body', 'body_top0', 'body_top1', 'body_bot', 'pelvis', 'neck0', 'head0', 'tail0')


def pose(offset=(0, 0, 0), body=(0, 0, 0), chest=0.0, neck=(0, 0, 0), head=(0, 0, 0), tail=(0, 0)):
    """Одна ключевая поза. chest раскладывается по груди и крупу, как body_pose."""
    return {
        'offset': tuple(offset),
        'angles': {
            'body': tuple(body),
            'body_top0': (chest, 0.0, 0.0),
            'body_top1': (chest * .35, 0.0, 0.0),
            'body_bot': (-chest * .3, 0.0, 0.0),
            'pelvis': (0.0, 0.0, 0.0),
            'neck0': tuple(neck),
            'head0': tuple(head),
            # хвост: как в body_pose — крен и половина его в рыскание
            'tail0': (tail[0], tail[1], tail[1] * .5),
        },
    }


# Ключевые позы. Кривые — BEZIER AUTO_CLAMPED: на разворотах (11, 17)
