"""Абордаж v3 (решения владельца 03.10): ключи новых клипов поверх принятых Abordage2 (ab_keys.py не меняется).

  Throw     0 стойка (тик каста C), 1 подъём, 2 ЧЕРЕЗ ПЛЕЧО (поза 10 листа B2: кисть над правым плечом и за ним,
            якорь висит на цепи за спиной), 3 ВЫПУСК (бросок сверху, ладонь раскрыта), 4 = кадр 3 принятого (проводка),
            9 = кадр 8 принятого (натяг) = кадр 0 Pull/PullShort. Замах 3 тика (цель за спиной — 4), выпуск — кадр 3.
  PullShort 0 натяг (= Throw 9), 1 рывок цепи, 2 НЫРОК (поза 9: низко, обе стопы в воздухе, левая вдоль цепи),
            3 = Pull 10 (взвод), 4 = Pull 11 (кулак пошёл), 5 = Pull 12 (КОНТАКТ) = Punch 0. Короткие тяги P = 3…5.
  Uppercut  0 = Pull 11 / PullShort 4 (тик B+P−1), 1 КОНТАКТ (B+P): низкий присед, кулак идёт вверх у подбородка,
            2 подъём (поза 7: кулак над головой), 3 опускание, 4 = Punch 3 = Recover 0 (B+P+3).
  Slam      0 = Pull 11 / PullShort 4, 1 КОНТАКТ: кулак в землю (поза 8), присед, 2 удержание, 3 подъём, 4 = Recover 0.
Пробоина — базовый Punch (без клипа).
"""
import math
import ab_keys
from ab_keys import stance, on_toe, chest_rel, crot, nrm, SU
from ab3_arm import K3, chest_dir, sw_for

P = "Pelag_AN_Abordage2_"


def slerp_dir(a, b, t):
    from mathutils import Vector
    va, vb = Vector(nrm(a)), Vector(nrm(b))
    return tuple(va.slerp(vb, t))


def clips(B):
    base = ab_keys.clips(B)
    S = stance(B)
    sL, sR = S["feet"]["Left"], S["feet"]["Right"]
    th, pu, pn = base[P + "Throw"], base[P + "Pull"], base[P + "Punch"]
    T3, T8 = th[3], th[8]
    P10, P11, P12 = pu[10], pu[11], pu[12]
    K3k = pn[3]
    k3 = lambda *a, **kw: K3(B, *a, **kw)

    # ---- Throw v3: замах через плечо 3 тика ---------------------------------------------------------------------
    rUp = (sR[0] - 0.03, sR[1] - 0.01, sR[2] + 0.09, sR[3], sR[4] + 3)       # правая стопа в воздухе весь замах
    rB2 = on_toe("Right", sR, 6, shift=(-0.10, -0.03))
    u2 = chest_dir(-60, -20, 10)
    W2 = k3(-0.04, -58, -60, 0, sL, rUp, u2, 95, (0.33, 0.07, -0.27), 0.66, 0.0, wd=20.0, sw=60.0)          # поза 10
    # кадр 1 — ровно середина стойка→поза 10 по каждой кости (путь 0→2 делится пополам: ≤ 35° за тик)
    W1 = {"slerp": (0, 2, 0.5), "plant": ("Left",), "foot_at": {"Right": (sR[0] - 0.015, sR[1] - 0.005, sR[2] + 0.075)}}
    # ВЫПУСК: бросок сверху — кисть выше и впереди плеча, ладонь раскрыта (перебор ab3_search_throw.py)
    R3 = k3(-0.07, -46, -22, 14, sL, rB2, chest_dir(-22, 45, 20), 55, (0.34, -0.03, -0.24), 1.0, -1.0, wd=32.0, sw=45.0)
    # проводка и возврат к натягу — по каждой кости от выпуска к натягу (A = 1 проходит 3→9 одним тиком без петли)
    throw = {0: S, 1: W1, 2: W2, 3: R3, 9: T8}
    for f, t in zip(range(4, 9), (0.42, 0.64, 0.80, 0.91, 0.97)):
        throw[f] = {"slerp": (3, 9, t), "plant": ("Left",)}

    # ---- PullShort: рывок, нырок вдоль короткой цепи, взвод/кулак/контакт принятой тяги -------------------------------
    # левая рука (кулак на цепи) — между натягом и взводом по каждой кости: P = 3 проходит 2→4 одним тиком без петли
    yR = sR[3]
    Y1 = k3(-0.02, -38, -14, 40, (0.42, 0.16, 0.27, sL[3], 4), (-0.52, -0.13, 0.30, yR, 16),
            (0.20, -0.36, -0.91), 84, chest_rel((0.44, 0.02, -0.18), 0, 6), 1.0, 0.5)                          # рывок
    Y1["mix"] = [("armL", 0, 2, 0.45), ("legs", 0, 2, 0.5)]
    D2 = k3(-0.05, -36, -14, 47, (0.40, 0.22, 0.22, sL[3], 2), (-0.56, -0.14, 0.30, yR, 24),
            (0.05, -0.40, -0.92), 92, (0.41, 0.05, -0.25), 1.0, 0.8)                                           # НЫРОК
    short = {0: T8, 1: Y1, 2: D2, 3: P10, 4: P11, 5: P12}

    # ---- Uppercut (Гейзер): из низкого приседа вверх ---------------------------------------------------------------
    # правая рука КОНТАКТА — ровно середина кулак пошёл → подъём (по каждой кости ≤ 70° за тик удара),
    # 3 — середина подъём → удержание Punch 3 (= Recover 0); левая с цепью — к бедру по прямой.
    rearR = on_toe("Right", sR, 22, shift=(-0.33, -0.04))
    sLl = (sL[0], sL[1], sL[2] + 0.004, sL[3], sL[4])          # глубокий присед: подошва не уходит под землю
    U1 = k3(-0.10, -22, 2, 14, sLl, rearR, (0.90, -0.42, -0.09), 100, (0.10, 0.18, -0.33), 1.0, 1.0, wd=32.0)  # КОНТАКТ
    U1["mix"] = [("armR", 0, 2, 0.52), ("armL", 0, 4, 0.55)]
    uU2 = (0.64, -0.16, 0.75); fU2 = (0.15, -0.05, 1.0)
    U2 = k3(-0.055, -18, 10, 6, sL, on_toe("Right", sR, 30, shift=(-0.33, -0.04)), uU2, 30, (0.06, 0.19, -0.36), 1.0, 1.0,
            wd=32.0, sw=sw_for(B, 10, uU2, 30, fU2))                                                              # поза 7
    U2["mix"] = [("armL", 0, 4, 0.85)]
    U3 = {"slerp": (2, 4, 0.5), "plant": ("Left", "Right")}
    upper = {0: P11, 1: U1, 2: U2, 3: U3, 4: K3k}

    # ---- Slam (Обвал): кулак в землю -------------------------------------------------------------------------------
    S1 = k3(-0.095, -24, 4, 62, sL, rearR, (0.20, -0.16, -0.97), 4, (0.16, 0.36, -0.26), 1.0, 1.0, wd=32.0)        # КОНТАКТ
    S2 = k3(-0.095, -24, 4, 63, sL, rearR, (0.21, -0.16, -0.97), 4, (0.15, 0.36, -0.27), 1.0, 1.0, wd=32.0)
    S1["ptilt"] = S2["ptilt"] = 0.10          # наклон — позвоночником, таз почти не валится: колено и пятка не плывут
    S3 = {"slerp": (2, 4, 0.5), "plant": ("Left", "Right")}
    slam = {0: P11, 1: S1, 2: S2, 3: S3, 4: K3k}

    out = dict(base)
    out[P + "Throw"] = throw
    out[P + "PullShort"] = short
    out[P + "Uppercut"] = upper
    out[P + "Slam"] = slam
    return out


DZ_FLOOR = {P + "Uppercut": -0.115, P + "Slam": -0.125}     # глубже принятого −0,075 — только новые клипы (таз ≤ 0,5)
