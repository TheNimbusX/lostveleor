"""Абордаж v2 (правка 02.10 по независимой проверке): ключевые позы листа B (позы 1–6) и раскладка клипов по тикам.

Оси корня: f — вперёд к цели, l — влево, u — вверх (метры v6). Сабля за кушаком у левого бедра (вид, BeginAnchorUse),
рукоять цепи в ЛЕВОМ кулаке (хват gL, ab_fingers.py), якорь бросает и бьёт ПРАВАЯ (gR: С-хват → ладонь → кулак).
Правая рука задаётся плечом u, сгибом локтя и плоскостью локтя b; b — плоскость стойки, повёрнутая вместе с грудью
(крутки плеча «сама собой» нет). Левая кисть — от левого плеча в осях корня.

Главное правило правки — путь кости за тик при ЛЮБОЙ раскладке (вид идёт по клипу по прямой во времени):
  * короткая тяга P = 2 проходит кадры 0→11 за один тик: каждая кость тела (не правая рука) от кадра 0 до 11 идёт
    в одну сторону и не дальше 35°; полёт — «срыв» 0→1 и дальше медленный дожим к кадру 11 (поза 4: взвод кулака,
    колени собраны, левый кулак выбирает цепь), 11→12 — удар и посадка;
  * бросок A = 1 проходит кадры 2→8 за тик: после выпуска всё идёт в одну сторону;
  * замах 0→1 — обычный тик (≤ 35°, как Load Шквала): корпус закручивается назад, правая подбирает якорь к плечу.
Клипы (кадр = тик при самой длинной раскладке):
  Throw   0 стойка, 1 замах (лист 1; правая стопа оторвана — вид крутит корень вокруг левой лодыжки), 2 выпуск (лист 2:
          ладонь раскрыта, правая стопа встала назад на носок), 3 рука прямая, 3–8 рука возвращается к груди, 8 натяг = Pull 0
  Pull    0 натяг, 1 срыв (лист 3), 1–10 дожим к позе 4, 10 взвод, 11 кулак пошёл, 12 КОНТАКТ (лист 5) = Punch 0
  Punch   0 контакт (левый кулак с цепью у бедра), 1–3 удержание
  Recover 0 = Punch 3, 1–2 шаг правой, 3 стойка листа 6 (кулаки в защите), 4–6 стойка серии сабли (= конец рывка/Шквала)
"""
import copy, math

FIST = (1.0, 0.0, 0.0)          # «клинок» решателя руки — правая без сабли, направление не ищется (рука задана arm)
TOE = {"Left": (0.630, 0.145, 0.004), "Right": (-0.171, -0.228, 0.004)}   # носки стойки (замер ab_probe)
UP = (0.0, 0.0, 1.0)
SU, SFLEX, SB = (-0.51, -0.26, -0.82), 48.2, (0.75, -0.59, -0.28)       # правая рука стойки (плечо, сгиб, плоскость)


def pose(dz, pyaw, cyaw, lean, L, R, hR, hL, arm=(0.0, 0.0, 32.0, 0.0), pR=(0.0, -0.6, -0.8), wp=0.0, W=1.0, look=0.0,
         gL=0.0, gR=0.0):
    p = dict(W=W, dz=dz, pyaw=pyaw, cyaw=cyaw, lean=lean, feet=dict(Left=L, Right=R), hands=dict(Right=hR, Left=hL),
             poles=dict(Right=pR, Left=(0.0, 0.6, -0.8)), blade=FIST, wB=0.0, look=look, sv=0.0, tv=0.0, wd=0.0, wf=0.0, wp=wp,
             gL=gL, gR=gR)
    p["arm"] = arm
    return p


def stance(B):
    """Стойка серии сабли на v6 (все слои с весом 0) — в ней кончаются рывок, Шквал и выход Абордажа."""
    ft = {s: (-B["ankle"][s].y, B["ankle"][s].x, B["ankle"][s].z, B["foot_yaw"][s], 0.0) for s in ("Left", "Right")}
    return pose(0.0, B["pyaw"], B["cyaw"], B["lean"], ft["Left"], ft["Right"], tuple(B["hand_rootR"]), tuple(B["hand_rootL"]),
                arm=(0.0, 0.0, 0.0, 0.0), W=0.0, look=B["head"]["faceYaw"])


def lerp_key(a, b, t):
    """Поза между двумя ключами (W = 1): числа — линейно."""
    L = lambda x, y: tuple(u + (v - u) * t for u, v in zip(x, y))
    q = copy.deepcopy(a)
    for k in ("dz", "pyaw", "cyaw", "lean", "look", "wp", "gL", "gR"):
        q[k] = a.get(k, 0.0) + (b.get(k, 0.0) - a.get(k, 0.0)) * t
    for grp in ("feet", "hands", "poles"):
        q[grp] = {s: L(a[grp][s], b[grp][s]) for s in a[grp]}
    q["arm"] = L(a.get("arm", (0, 0, 0, 0)), b.get("arm", (0, 0, 0, 0)))
    q["W"] = 1.0
    q.pop("fixed", None)
    return q


def on_toe(side, ankle, deg, shift=(0.0, 0.0), lift=0.0):
    """Пятка вверх на deg вокруг носка (носок стойки, сдвинутый на shift по f, l): носок стоит, лодыжка поднимается.
    lift — вся стопа выше земли (м), для стопы в воздухе."""
    tf, tl, tu = TOE[side]
    tf, tl = tf + shift[0], tl + shift[1]
    af, al, au = ankle[0] + shift[0], ankle[1] + shift[1], ankle[2]
    df, dl, du = af - tf, al - tl, au - tu
    h = math.hypot(df, dl)
    a = math.radians(deg)
    nh = h * math.cos(a) - du * math.sin(a)
    nu = h * math.sin(a) + du * math.cos(a)
    return (tf + df / h * nh, tl + dl / h * nh, tu + nu + lift, ankle[3], ankle[4] + deg)


def crot(v, deg):
    """Повернуть вектор осей корня вокруг вертикали на deg (+ к левому боку)."""
    a = math.radians(deg); c, s = math.cos(a), math.sin(a)
    return (v[0] * c - v[1] * s, v[0] * s + v[1] * c, v[2])


def nrm(v):
    n = math.sqrt(sum(c * c for c in v))
    return tuple(c / n for c in v)


def tilt(v, to, deg):
    """Повернуть единичный v к направлению to на deg в их общей плоскости."""
    from mathutils import Vector
    v, to = Vector(nrm(v)), Vector(nrm(to))
    w = (to - to.dot(v) * v)
    if w.length < 1e-6: return tuple(v)
    w.normalize(); a = math.radians(deg)
    return tuple(v * math.cos(a) + w * math.sin(a))


def chest_rel(v, dcy, dlean):
    """Кисть от плеча, заданная в осях груди натяга: повернуть с грудью (рысканье dcy, наклон вперёд dlean) в оси корня."""
    f, l, u = crot(v, dcy)
    a = math.radians(dlean)
    return (f * math.cos(a) + u * math.sin(a), l, -f * math.sin(a) + u * math.cos(a))


def arm(u, flex, b):
    """Правая рука по плечевой кости: u — куда смотрит плечо (осями корня), flex — сгиб локтя (°), b — куда складывается
    предплечье. Возвращает (кисть от плеча v, полюс локтя) — для pose(hR=v, pR=полюс, wp=1)."""
    from mathutils import Vector
    u = Vector(u).normalized(); b = Vector(b); b = (b - b.dot(u) * u).normalized()
    a = math.radians(flex)
    f = u * math.cos(a) + b * math.sin(a)
    v = u * 0.254 + f * 0.255
    vn = v.normalized()
    pole = u - u.dot(vn) * vn
    return tuple(round(c, 4) for c in v), tuple(round(c, 4) for c in pole.normalized())


def clips(B):
    """Все клипы: имя → {кадр: поза}. Кадры между ключами — монотонная кубика по каждому числу (ab_measure.sample)."""
    S = stance(B)
    sL, sR = S["feet"]["Left"], S["feet"]["Right"]
    cy0 = B["cyaw"]

    def K(dz, pyaw, cyaw, lean, L, R, u, flex, hL, gL, gR, wd=32.0):
        """Правая рука: плечо u (оси корня), сгиб; плоскость локтя — плоскость стойки, повёрнутая с грудью и
        перенесённая кратчайшим поворотом плеча (без крутки: нормаль шарнира едет за плечом)."""
        from mathutils import Vector
        us, bs = Vector(crot(SU, cyaw - cy0)).normalized(), Vector(crot(SB, cyaw - cy0))
        n0 = us.cross(bs).normalized()
        uu = Vector(nrm(u))
        n = us.rotation_difference(uu) @ n0
        v, pole = arm(tuple(uu), flex, tuple(n.cross(uu)))
        # wd — кисть от стойки к прямому запястью (32° = покой): кулак бьёт прямой кистью, в стойке — отведена под саблю
        return pose(dz, pyaw, cyaw, lean, L, R, v, hL, arm=(0.0, 0.0, wd, 0.0), pR=pole, wp=1.0, gL=gL, gR=gR)

    rB = on_toe("Right", sR, 10, shift=(-0.10, -0.03))          # правая шагнула назад на носок (выпуск → натяг)
    rearR = on_toe("Right", sR, 22, shift=(-0.33, -0.04))        # выпад листа 5: правая далеко сзади на носке
    rB2 = on_toe("Right", sR, 6, shift=(-0.10, -0.03))
    rUp = (sR[0] - 0.04, sR[1] - 0.01, sR[2] + 0.07, sR[3], sR[4] + 3)    # замах: правая стопа оторвана (вверх, не по земле)
    yR = sR[3]

    # ---- Throw: замах 1 тик (≤ 35°), выпуск, рука прямая, возврат к груди за полёт якоря, натяг ---------------
    T1 = K(-0.03, -55, -62, -5, sL, rUp, tilt(crot(SU, -32), UP, 26), 76, (0.31, -0.02, -0.31), 0.34, 0.0, 18)  # лист 1
    T2 = K(-0.07, -45, -18, 17, sL, rB2, (0.33, -0.93, 0.04), 40, (0.34, -0.03, -0.24), 0.68, -1.0)         # лист 2
    T3 = K(-0.08, -41, -8, 20, sL, rB, (0.70, -0.60, -0.12), 18, (0.37, -0.01, -0.22), 1.0, -0.85)
    T8 = K(-0.09, -36, -14, 23, sL, rB, (0.70, -0.32, -0.58), 58, (0.41, 0.00, -0.20), 1.0, 0.0)            # натяг
    throw = {0: S, 1: T1, 2: T2, 3: T3, 8: T8}

    # ---- Pull: срыв, дожим к позе 4 (кадры 1–10 в одну сторону), кулак пошёл, контакт ---------------------------
    P1 = K(0.03, -38, -14, 35, (0.42, 0.16, 0.285, sL[3], 2), (-0.48, -0.13, 0.35, yR, 18),
           (0.30, -0.34, -0.89), 78, chest_rel((0.40, 0.01, -0.22), 0, 7), 1.0, 0.5)                                       # лист 3
    P10 = K(0.04, -37, -16, 36, (0.43, 0.16, 0.31, sL[3], -2), (-0.54, -0.13, 0.39, yR, 22),
            (-0.08, -0.42, -0.90), 94, chest_rel((0.32, 0.04, -0.28), -2, 8), 1.0, 0.95)                                      # лист 4: взвод
    P11 = K(0.02, -33, -17, 31, (0.45, 0.16, 0.285, sL[3], -4), (-0.55, -0.13, 0.34, yR, 22),
            (0.40, -0.32, -0.85), 74, chest_rel((0.26, 0.07, -0.33), -3, 5), 1.0, 1.0)                                       # кулак пошёл
    P12 = K(-0.10, -16, 10, 15, sL, rearR, (0.99, 0.02, -0.12), 8, (0.11, 0.17, -0.31), 1.0, 1.0)            # лист 5: КОНТАКТ
    pull = {0: T8, 1: P1, 10: P10, 11: P11, 12: P12}

    # ---- Punch: контакт и 3 тика удержания ------------------------------------------------------------------------
    K1 = K(-0.10, -16, 13, 15, sL, rearR, (0.99, 0.02, -0.15), 10, (0.08, 0.18, -0.33), 1.0, 1.0)
    K3 = K(-0.10, -18, 11, 14, sL, rearR, (0.97, 0.00, -0.24), 14, (0.06, 0.18, -0.33), 1.0, 1.0)
    punch = {0: P12, 1: K1, 3: K3}

    # ---- Recover: шаг правой (носок сначала вверх), стойка листа 6 (кулаки в защите), стойка серии сабли --------
    R1 = K(-0.09, -26, -4, 12, sL, (rearR[0] + 0.03, rearR[1], rearR[2] + 0.07, rearR[3], rearR[4] - 14),
           (0.70, -0.12, -0.70), 48, (0.12, 0.16, -0.30), 1.0, 1.0)
    R2 = K(-0.07, -36, -14, 9, sL, (-0.32, -0.10, 0.24, -55, 4), (0.30, -0.20, -0.93), 80, (0.20, 0.10, -0.26), 1.0, 1.0)
    R3 = K(-0.05, -45, -22, 8, sL, sR, (0.08, -0.25, -0.96), 100, (0.28, 0.02, -0.14), 1.0, 1.0)            # лист 6
    R4 = K(-0.03, -48, -25, 7.5, sL, sR, (-0.18, -0.26, -0.95), 88, (0.30, 0.07, -0.26), 0.66, 0.66, 22)
    R5 = K(-0.015, -51, -28, 7, sL, sR, (-0.38, -0.26, -0.88), 66, (0.31, 0.10, -0.33), 0.33, 0.33, 11)
    recover = {0: K3, 1: R1, 2: R2, 3: R3, 4: R4, 5: R5, 6: S}
    P = "Pelag_AN_Abordage2_"
    return {P + "Throw": throw, P + "Pull": pull, P + "Punch": punch, P + "Recover": recover}
