def ch(knots, t):
    """Канал по ключам (монотонная кубика), вектор — покомпонентно; вне ключей — крайние значения."""
    v0 = knots[0][1]
    if isinstance(v0, (tuple, list)):
        return tuple(pchip([(k, v[c]) for k, v in knots], t) for c in range(len(v0)))
    return pchip(knots, t)


def wrap(e):
    return (e + 180.0) % 360.0 - 180.0


def smooth01(x):
    x = max(0.0, min(1.0, x)); return x * x * (3 - 2 * x)


def mix(a, b, w):
    """Поза a → b с весом w (кости — slerp, смещения — lerp); ключи с «_» берутся из b."""
    if w <= 0.0: return dict(a)
    if w >= 1.0: return dict(b)
    out = dict(b)
    for n, (lb, qb) in b.items():
        if n.startswith("_"): continue
        la, qa = a[n]
        if qa.dot(qb) < 0: qb = -qb
        out[n] = (la.lerp(lb, w), qa.slerp(qb, w))
    return out


