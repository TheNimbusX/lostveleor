"""Крушение v2: ключи клипов форм по листу B2 (позы 8–11) поверх базы (wk_clipkeys). Кадр = тик, корень стоит.

Charge (Девятый вал, 0..12, цикл 12 = 0, поза 8): «вертолёт» — кулаки над лбом петлёй 0,38 × 0,26 м за оборот (anchor-core
  §6.1: петля 0,15–0,25; наклонена — сзади выше, у лба сзади-слева поджата, иначе предплечья в волосах), рукоять стоймя с наклоном 22° вперёд, кольцо сверху, правый кулак на цепи у самого кольца
  (зазор 0,125): цепь от кольца уходит вбок к голове якоря в любую сторону, кулаки вокруг вертикали не проворачиваются
  (рукоять по цепи, как в листе, кулаками на 360° не провернуть). Голова отстаёт от кулаков на ≈ 60° — хват тянет её по
  кругу ≈ 2 м над героем (проверочный кистень: петля держит 30–32 м/с при сопротивлении воздуха; меньшая петля
  — голова гаснет за 3 оборота); путь даст запечка. Очень низкая широкая стойка, стопы плашмя. Вход — из Slam кадр 5 (тик
  «над головой»): правая стоит там же (rBack), левая заканчивает шаг шире вперёд-влево; вид смешивает 2–3 кадра.
ChargeRelease (0..15, контакт 4, поза 9): 0 = Charge 3 (фаза отпускания); рывок вниз-вперёд (0–4), правая шагает назад и встаёт на носок —
  выпад шире и глубже Slam, цепь на всю длину (2,6 м); удержание 5–7; выход 8–15 в позу 7 (кадр 13), 15 = Slam 20.
Swing1_Braced / Swing2_Braced (Панцирь, поза 10): верх тела и хват — копия ключей базы; таз ниже, корпус чуть
  ссутулен (кисти ниже вместе с грудью), стопы плашмя (без носка). Ведущая нога меняется теми же шагами по 4 тика,
  но раньше: правая — вперёд-вправо в снятии (0→4, мах 1 из широкой стойки), левая — назад 2→6 Swing2 (в контакте 6
  обе стопы на земле, поза 10).
  Стыки — кадры базы: Swing1_Braced 0 = стойка, 8 = Swing2_Braced 0, 12 = Swing1 12 (Wait1 0), Swing2_Braced 7 =
  Swing2 7 (Slam 0), 11 = Swing2 11 (Wait2 0).
Slam_Drag (Волнорез, 0..21, контакт 9): 0–12 — кадры Slam (11 копируется снимком в wk_author), 13–16 правая с носка
  коротким шагом вперёд и плашмя — выпад остаётся широким, как в листе (без проезда корня), руки тянутся вперёд-вниз по натянутой цепи, наклон ~41° (поза 11
  в 16), 17 — протяжка, 18–21 возврат в Slam 20 (= Stow 0); держит героя по кадр 18.
"""
import copy, math
from wk_keys import key, step, SFX, GAP, nrm
from wk_clips import SL, SR, SPINE, on_toe, rot, cr, P_FRONT, P_OVER

EXTRA = 0.05                     # Панцирь: таз ниже базы (DZ_MIN −0,13 держит смещение таза ≤ 0,5)
HUNCH = 4.0                      # Панцирь: плечи вперёд (°)
CH_DZ = -0.125                   # Девятый вал: самый низкий таз в пределе 0,5
CH_R, CH_LEAD, CH_GAP = 0.19, 60.0, 0.125
CH_LEAN = 2.0                    # корпус почти прямой (поза 8), лицо дальше от предплечий
CH_TU = 0.10                     # петля наклонена: у головы (сзади) выше, спереди ниже — предплечья над чёлкой
CH_BL = 0.5                      # четверть «сзади-слева» петли (правая рука тянется через лоб) — меньше
CH_TL = 0.05                     # петля выше слева (правое предплечье через лицо не идёт)
CH_RF = 0.13                     # петля вперёд-назад (эллипс: к голове ближе нельзя — руки в волосы)
CH_C = (0.50, -0.08, 1.62)       # центр петли левого кулака — над лбом, впереди головы (оси корня f, l, u)
CH_E = (0.40, 0.0, 1.0)          # ось рукояти от груди (f, l, u): стоймя, 22° вперёд
CH_POLES = ((0.6, 0.8, -0.2), (0.6, -0.8, -0.2))   # локти вперёд-в стороны
CH_A0 = 220.0                    # азимут кулаков в кадре 0 (голова якоря ≈ 160°, за спиной); оборот против часовой сверху
CH_REL = 3                       # кадр цикла = кадр 0 ChargeRelease: голова справа идёт вперёд — за 4 тика приходит
                                 # вперёд (wk_finish: charge_release_by_phase); из других фаз вид смешивает 2 кадра


def forms(B, SF, base):
    s1, s2, sl = base[SFX + "Swing1"], base[SFX + "Swing2"], base[SFX + "Slam"]

    def K(dz, pyaw, cyaw, lean, L, R, hands, poles, **kw):
        return key(dz, pyaw, cyaw, lean, L, R, hands, (rot(poles[0], cyaw), rot(poles[1], cyaw)), **kw)

    def g(f, l, u, cy, head):
        G = cr(f, l, u, cy)
        d = nrm(tuple(h - x for h, x in zip(head, G)))
        return dict(Left=G, Right=tuple(x + GAP * c for x, c in zip(G, d))), dict(Left=d, Right=d), d

    # ---------------------------------------------------------------- Панцирь: копия ключа базы, ниже и плашмя
    def brace(k, extra, L=None, R=None, hunch=None):
        q = copy.deepcopy({kk: v for kk, v in k.items() if kk != "hint_from"})
        q["sol"] = None; q["hint"] = {}; q["hint_from"] = k
        q["dz"] = max(-0.13, k["dz"] - extra)
        q["lean"] = k["lean"] + (HUNCH * extra / EXTRA if hunch is None else hunch)
        dd = q["dz"] - k["dz"]                                            # грудь ниже на dd — кисти и плановая голова тоже
        q["hand"] = {s_: (v[0], v[1], v[2] + dd) for s_, v in q["hand"].items()}
        if L is not None: q["feet"]["Left"] = tuple(L)
        if R is not None: q["feet"]["Right"] = tuple(R)
        return q

    rLand = (0.22, -0.22, 0.136, -40.0, 0.0)
    lBack = (0.00, 0.22, 0.136, -20.0, 0.0)
    b1 = {0: s1[0]}
    for f, e in ((1, 0.0), (2, 0.025), (3, 0.05)):                        # правая шагает вперёд-вправо в снятии 0→4
        b1[f] = brace(s1[f], e, R=step(SR, rLand, f / 4.0, 0.07))
    for f in range(4, 12):                                                # мах 1 и проводка: обе стопы плашмя
        up = {4: .003, 5: .003, 6: .003, 7: .0015}.get(f, 0.0)            # таз крутится над плоской стопой — лодыжка чуть выше
        b1[f] = brace(s1[f], 0.05 if f < 11 else 0.045, R=(rLand[0], rLand[1], rLand[2] + up, rLand[3], rLand[4]))
    b1[12] = s1[12]                                                       # = Swing1 12 (Wait1 0)
    b2 = {0: b1[8], 1: b1[9]}
    b2[2] = brace(s2[2], 0.05, L=SL, R=rLand)
    for f, t in ((3, .25), (4, .5), (5, .75)):                            # левая назад 2→6, встаёт в контакт
        b2[f] = brace(s2[f], 0.05, L=step(SL, lBack, t, 0.065, 2), R=rLand, hunch=1.0)   # кисти у плеча — голову не горбить
    b2[6] = brace(s2[6], 0.06, L=lBack, R=rLand)                          # поза 10 КОНТАКТ: обе стопы плашмя
    b2[7] = s2[7]                                                         # = Swing2 7 (Slam 0)
    b2[9] = s2[9]
    b2[11] = s2[11]                                                       # = Swing2 11 (Wait2 0)

    # ---------------------------------------------------------------- Девятый вал: вертолёт (поза 8)
    rBack = (-0.22, -0.15, 0.136, -55.0, 0.0)
    CL = (0.50, 0.30, 0.136, -14.0, 0.0)                                  # левая шире вперёд-влево (шаг из Slam 5)
    CH_PY, CH_CY = -16.0, -6.0
    ch = {}
    for f in range(12):
        ph = 2 * math.pi * f / 12
        a = math.radians(CH_A0) + ph                                      # кулаки петлёй над головой
        ah = a - math.radians(CH_LEAD)                                    # голова якоря отстаёт: цепь тянет её по кругу
        q_ = 1.0 - (1.0 - CH_BL) * max(0.0, -math.cos(a)) * max(0.0, math.sin(a)) * 2.0   # петля поджата сзади-слева, гладко
        G = (CH_C[0] + q_ * CH_RF * math.cos(a), CH_C[1] + q_ * CH_R * math.sin(a),
             CH_C[2] - CH_TU * math.cos(a) + CH_TL * math.sin(a) + 0.010 * math.sin(2 * ph))
        cyaw = CH_CY + 5.0 * math.sin(a)                                  # грудь чуть за кулаками
        e = nrm(tuple(rot(CH_E, cyaw)))                                   # рукоять стоймя (кольцо сверху)
        chain = nrm((math.cos(ah), math.sin(ah), -0.03))                  # цепь от кольца — вбок к голове (план)
        hands = (dict(Left=G, Right=tuple(x + CH_GAP * c for x, c in zip(G, e))), dict(Left=e, Right=e), chain)
        ch[f] = K(CH_DZ + 0.006 * math.cos(2 * ph), CH_PY + 2.5 * math.sin(a), cyaw, CH_LEAN + 1.0 * math.cos(a),
                  CL, rBack, hands, CH_POLES)
        ch[f]["gap"] = CH_GAP; ch[f]["axw"] = {"Right": 0.6}                # правый кулак держит ось рукояти сильнее
    ch[12] = ch[0]

    # ---------------------------------------------------------------- Девятый вал: отпускание (поза 9)
    rL = (-0.44, -0.22, 0.136, -58.0, 0.0)
    rLT = lambda p: on_toe("Right", rL, p)
    CLu = lambda e: (CL[0], CL[1], CL[2] + e, CL[3], CL[4])     # выпад: кожа голени у лодыжки — лодыжка выше
    cr_ = {0: ch[CH_REL]}
    cr_[1] = K(-0.125, -8, -3, 9, CLu(0.0), step(rBack, rL, 1 / 3, 0.06), g(0.56, 0.02, 1.50, -3, (-0.4, -0.3, 3.6)), P_OVER)
    cr_[2] = K(-0.125, -5, 0, 19, CLu(.003), step(rBack, rL, 2 / 3, 0.06), g(0.66, 0.00, 1.16, 0, (1.4, -0.1, 3.2)), P_FRONT)
    cr_[3] = K(-0.13, -3, 2, 29, CLu(.008), rL, g(0.60, 0.00, 0.86, 2, (2.35, 0.0, 1.9)), P_FRONT)
    cr_[4] = K(-0.13, -1, 3, 38, CLu(.009), rLT(14), g(0.56, 0.00, 0.79, 3, (2.65, 0.0, 0.32)), P_FRONT)        # поза 9 КОНТАКТ
    cr_[5] = K(-0.13, 0, 3, 41, CLu(.009), rLT(20), g(0.58, 0.00, 0.76, 3, (2.62, 0.0, 0.32)), P_FRONT)
    cr_[7] = K(-0.13, 0, 2, 40, CLu(.009), rLT(20), g(0.60, 0.00, 0.76, 2, (2.60, 0.0, 0.32)), P_FRONT)
    cr_[8] = K(-0.12, -6, -6, 36, CLu(0.008), step(rLT(20), SR, .25, 0.06), g(0.58, -0.05, 0.78, -6, (2.4, -0.05, 0.32)), P_FRONT)
    cr_[9] = K(-0.11, -14, -14, 30, CLu(0.006), step(rLT(20), SR, .5, 0.06), g(0.50, -0.08, 0.81, -14, (2.2, -0.1, 0.32)), P_FRONT)
    cr_[10] = K(-0.10, -24, -22, 24, CLu(0.004), step(rLT(20), SR, .75, 0.06), g(0.44, -0.10, 0.84, -22, (1.9, -0.2, 0.32)), P_FRONT)
    cr_[11] = K(-0.085, -32, -28, 19, CLu(0.002), SR, g(0.43, -0.11, 0.86, -28, (1.6, -0.3, 0.32)), P_FRONT)
    cr_[12] = K(-0.07, -38, -33, 15, step(CL, SL, 1 / 3, 0.04), SR, g(0.45, -0.12, 0.88, -33, (1.35, -0.38, 0.32)), P_FRONT)
    cr_[13] = K(-0.055, -45, -36, 12, step(CL, SL, 2 / 3, 0.04), SR, g(0.46, -0.12, 0.90, -36, (1.2, -0.4, 0.32)), P_FRONT)  # поза 7
    cr_[14] = K(-0.04, -49, -35, 10, SL, SR, g(0.46, -0.13, 0.91, -35, (1.1, -0.45, 0.32)), P_FRONT)
    for f in range(1, 15):                                                # руки плавно из ветки заряда в ветку Slam 20
        if f in cr_: cr_[f]["hint_mix"] = (ch[CH_REL], sl[20], f / 15.0)
    cr_[15] = sl[20]                                                     # = Slam 20 (Stow 0)

    # ---------------------------------------------------------------- Волнорез: протяжка (поза 11)
    rBT = on_toe("Right", rBack, 22)
    rDrag = (-0.10, -0.25, 0.136, -45.0, 0.0)                              # короткий шаг: стойка остаётся широкой (лист B2, поза 11)
    SLl = (SL[0], SL[1], SL[2] + 0.006, SL[3], SL[4])
    dr = {f: sl[f] for f in sl if f <= 12}
    dr[13] = K(-0.11, 0, 3, 41, SLl, step(rBT, rDrag, .25, 0.06), g(0.58, 0.00, 0.78, 3, (2.30, 0.0, 0.32)), P_FRONT)
    dr[14] = K(-0.11, 0, 2, 42, SLl, step(rBT, rDrag, .5, 0.06), g(0.63, 0.00, 0.76, 2, (2.40, 0.0, 0.32)), P_FRONT)
    dr[15] = K(-0.11, 0, 2, 42, SLl, step(rBT, rDrag, .75, 0.06), g(0.66, 0.00, 0.75, 2, (2.50, 0.0, 0.32)), P_FRONT)
    dr[16] = K(-0.11, 0, 2, 41, SLl, rDrag, g(0.68, 0.00, 0.74, 2, (2.60, 0.0, 0.32)), P_FRONT)            # поза 11
    dr[17] = K(-0.105, -2, 0, 39, SLl, rDrag, g(0.64, -0.01, 0.76, 0, (2.60, 0.0, 0.32)), P_FRONT)
    dr[18] = K(-0.09, -14, -10, 32, SL, step(rDrag, SR, .25, 0.09), g(0.56, -0.05, 0.80, -10, (2.4, -0.1, 0.32)), P_FRONT)
    dr[19] = K(-0.07, -28, -20, 23, SL, step(rDrag, SR, .5, 0.09), g(0.50, -0.09, 0.84, -20, (2.0, -0.2, 0.32)), P_FRONT)
    dr[20] = K(-0.05, -42, -28, 15, SL, step(rDrag, SR, .75, 0.09), g(0.47, -0.12, 0.88, -28, (1.5, -0.35, 0.32)), P_FRONT)
    dr[21] = sl[20]                                                       # = Slam 20 (Stow 0)

    return {SFX + "Charge": ch, SFX + "ChargeRelease": cr_, SFX + "Swing1_Braced": b1, SFX + "Swing2_Braced": b2,
            SFX + "Slam_Drag": dr}


COPY_FRAMES = {SFX + "Slam_Drag": (SFX + "Slam", 0, 12)}     # кадры клипа = снимки другого клипа (точная копия)
