"""Крушение v2: ключи клипов по листам B (позы 1–7). Кисти и локти — от груди (wk_clips.cr / rot), голова якоря —
плановая точка в осях корня (только ось цепи). Номера поз листа — в комментариях."""
from wk_keys import key, grip, stance, step, lerp_key, SFX
from wk_clips import SL, SR, SPINE, on_toe, rot, cr, P_FRONT, P_MID, P_LSH, P_OVER, P_DRAW, P_DRAW1


def clips(B, SF):
    S = stance(B, SF)

    def K(dz, pyaw, cyaw, lean, L, R, hands, poles, **kw):
        """Ключ: кисти и локти заданы от груди (повёрнуты на рысканье груди cyaw)."""
        return key(dz, pyaw, cyaw, lean, L, R, hands, (rot(poles[0], cyaw), rot(poles[1], cyaw)), **kw)

    def KS(dz, pyaw, cyaw, lean, L, R, *a, **kw):
        return K(dz, pyaw, cyaw, lean, (L[0], L[1], L[2] + 0.002, L[3], L[4]) if L is SL else L, R, *a, **kw)

    def g(f, l, u, cy, head):
        return grip(cr(f, l, u, cy), head)

    def to_chest(v, cy):
        x, y = rot((-v.y - SPINE[0], v.x - SPINE[1]), -cy)
        return (x, y, v.z)

    def to_chest_dir(v, cy, root=False):
        f_, l_, u_ = (v if root else (-v.y, v.x, v.z))
        x, y = rot((f_, l_), -cy)
        return (x, y, u_)

    def free(lf, rf, lax, rax, cy):
        return dict(Left=cr(*lf, cy), Right=cr(*rf, cy)), dict(Left=rot(lax, cy), Right=rot(rax, cy))

    DRAW1 = ((0.46, 0.10, 0.96), (0.30, -0.25, 0.98), (0.0, -0.2, -0.98), (0.3, -0.3, -0.9))
    DRAW2 = ((0.32, -0.16, 1.22), (0.34, -0.30, 1.02), (0.30, -0.20, -0.93), (0.50, -0.30, -0.80))
    P_POSE1 = ((0.40, 0.50, -0.75), (-0.10, -0.70, -0.70))

    # ---- Swing1: снятие со спины (0–2: левая через грудь к правому плечу, 2 — рукоять с крепления), поза 1 (3),
    #      мах справа налево (3–7, КОНТАКТ 7), проводка (8–12, поза 3 в 10) ------------------------------------------------
    rT = lambda pt, dy: on_toe("Right", SR, pt, dy)
    rT7 = rT(22, 20)
    rLand = (0.22, -0.22, 0.136, -40.0, 0.0)
    SLs = (SL[0], SL[1], SL[2] + 0.002, SL[3], SL[4])
    s1 = {0: S}
    s1[1] = K(-0.02, -56, -38, 7, SL, SR, free(*DRAW1, -38), P_DRAW1, gL=0.3, gR=0.3, handle=False)
    s1[2] = K(-0.03, -60, -45, 8, SL, SR, free(*DRAW2, -45), P_DRAW, gL=0.7, gR=0.7, handle=False)           # снятие
    s1[3] = KS(-0.05, -66, -100, 10, SL, SR, g(0.30, -0.05, 0.98, -100, (-1.05, -1.82, 0.55)), P_POSE1)            # поза 1
    s1[4] = KS(-0.05, -45, -64, 12, SL, rT(8, 6), g(0.40, -0.05, 0.94, -64, (0.30, -2.20, 0.70)), P_FRONT)
    s1[5] = KS(-0.06, -24, -22, 13, SL, rT(14, 11), g(0.45, 0.00, 0.93, -22, (1.50, -1.75, 0.80)), P_FRONT)
    s1[6] = KS(-0.06, -8, 12, 14, SL, rT(19, 16), g(0.48, 0.05, 0.93, 12, (2.15, -0.90, 0.80)), P_FRONT)
    s1[7] = KS(-0.06, 4, 36, 15, SL, rT7, g(0.48, 0.10, 0.93, 36, (2.35, 0.00, 0.80)), P_FRONT)                  # поза 2 КОНТАКТ
    s1[8] = KS(-0.07, 12, 46, 13, SL, step(rT7, rLand, .25, 0.07), g(0.48, 0.12, 0.98, 46, (2.05, 1.05, 0.90)), P_FRONT)
    s1[9] = KS(-0.08, 14, 50, 10, SL, step(rT7, rLand, .5, 0.07), g(0.45, 0.10, 1.01, 50, (1.80, 1.40, 0.95)), P_FRONT)
    s1[10] = KS(-0.08, 14, 50, 9, SL, step(rT7, rLand, .75, 0.07), g(0.42, 0.05, 0.97, 50, (0.20, 1.90, 0.90)), P_FRONT)  # поза 3
    s1[11] = KS(-0.075, 13, 49, 8.5, SL, rLand, g(0.42, 0.04, 0.96, 49, (-0.20, 1.60, 0.60)), P_FRONT)
    s1[12] = KS(-0.07, 12, 48, 8, SL, rLand, g(0.42, 0.04, 0.95, 48, (-0.50, 1.40, 0.35)), P_FRONT)

    # ---- Swing2: восьмёрка через левое плечо (0–1 = Swing1 8–9, 3 — кисти у левого плеча, КОНТАКТ 6), левая назад 2–5 ----
    lBack = (0.00, 0.22, 0.136, -20.0, 0.0)
    s2 = {0: s1[8], 1: s1[9]}
    s2[2] = K(-0.08, 14, 46, 8, SL, step(rT7, rLand, .75, 0.07), g(0.42, 0.16, 1.20, 46, (0.00, 1.60, 2.30)), P_MID)
    s2[3] = K(-0.07, 6, 34, 7, SL, rLand, g(0.46, 0.20, 1.34, 34, (-0.80, 0.90, 2.90)), P_LSH)
    s2[4] = K(-0.06, -8, 8, 10, step(SL, lBack, .25, 0.07, 4), rLand, g(0.46, 0.10, 1.26, 8, (0.90, 0.90, 3.00)), P_LSH)
    s2[5] = K(-0.06, -22, -24, 13, step(SL, lBack, .5, 0.07, 4), rLand, g(0.45, 0.00, 1.08, -24, (2.00, 0.70, 1.90)), P_FRONT)
    s2[6] = K(-0.06, -32, -52, 15, step(SL, lBack, .75, 0.07, 4), rLand, g(0.45, -0.05, 0.98, -52, (2.35, 0.00, 0.75)), P_FRONT)        # поза 4 КОНТАКТ
    s2[7] = K(-0.05, -40, -72, 12, lBack, rLand, g(0.40, -0.06, 1.02, -72, (2.00, -1.00, 0.60)), P_FRONT)
    s2[9] = K(-0.04, -44, -80, 10, lBack, rLand, g(0.36, -0.05, 0.95, -80, (0.60, -1.90, 0.60)), P_FRONT)
    s2[11] = K(-0.04, -42, -78, 8, lBack, rLand, g(0.34, -0.05, 0.93, -78, (-0.50, -1.60, 0.35)), P_FRONT)

    # ---- Slam: правая назад (0–2), левая вперёд (2–5), дуга над головой (поза 5 в 5), вниз (6–9, КОНТАКТ 9, поза 6),
    #      удержание 10–12, выход 13–20 (правая к стойке 13–16, поза 7 в 18) ---------------------------------------------
    rBack = (-0.22, -0.15, 0.136, -55.0, 0.0)
    rToe = lambda p: on_toe("Right", rBack, p)
    SLl = (SL[0], SL[1], SL[2] + 0.006, SL[3], SL[4])          # выпад: кожа голени у лодыжки уходит в землю — лодыжка на 6 мм выше
    sl = {0: s2[7]}
    sl[1] = K(-0.04, -36, -66, 8, lBack, step(rLand, rBack, .25, 0.07), g(0.36, -0.10, 1.26, -66, (1.20, -1.70, 0.90)), P_FRONT)
    sl[2] = K(-0.03, -28, -48, 5, lBack, step(rLand, rBack, .5, 0.07), g(0.40, -0.12, 1.42, -48, (0.00, -1.60, 1.90)), P_MID)
    sl[3] = K(-0.03, -20, -30, 3, lBack, step(rLand, rBack, .75, 0.07), g(0.44, -0.04, 1.62, -30, (-1.20, -0.60, 2.60)), P_OVER)
    sl[4] = K(-0.03, -14, -16, 2, lBack, rBack, g(0.40, 0.00, 1.74, -16, (-1.30, -0.20, 3.00)), P_OVER)
    sl[5] = K(-0.03, -10, -8, 2, step(lBack, SL, .25, 0.06, -10), rBack, g(0.42, 0.02, 1.74, -8, (-1.20, 0.00, 3.20)), P_OVER)                # поза 5
    sl[6] = K(-0.05, -6, -2, 9, step(lBack, SL, .5, 0.06, -10), rBack, g(0.50, 0.02, 1.64, -2, (-0.30, 0.00, 3.60)), P_OVER)
    sl[7] = K(-0.08, -3, 2, 19, step(lBack, SL, .75, 0.06, -10), rToe(6), g(0.62, 0.00, 1.44, 2, (1.60, 0.00, 3.10)), P_FRONT)
    sl[8] = K(-0.10, -1, 4, 28, SLl, rToe(14), g(0.60, 0.00, 1.20, 4, (2.20, 0.00, 1.90)), P_FRONT)
    sl[9] = K(-0.11, 0, 5, 36, SLl, rToe(20), g(0.50, 0.00, 1.00, 5, (2.25, 0.00, 0.35)), P_FRONT)            # поза 6 КОНТАКТ
    sl[10] = K(-0.11, 0, 5, 40, SLl, rToe(22), g(0.52, 0.00, 0.86, 5, (2.20, 0.00, 0.32)), P_FRONT)
    sl[12] = K(-0.11, 0, 4, 39, SLl, rToe(22), g(0.54, 0.00, 0.80, 4, (2.20, 0.00, 0.32)), P_FRONT)
    sl[13] = K(-0.10, -6, -4, 35, SLl, rToe(10), g(0.48, -0.05, 0.81, -4, (2.10, 0.00, 0.32)), P_FRONT)
    sl[14] = K(-0.09, -16, -16, 29, SL, step(rToe(10), SR, 1 / 3), g(0.42, -0.08, 0.82, -16, (2.00, -0.05, 0.32)), P_FRONT)
    sl[15] = K(-0.08, -24, -24, 24, SL, step(rToe(10), SR, 2 / 3), g(0.40, -0.10, 0.84, -24, (1.80, -0.15, 0.32)), P_FRONT)
    sl[16] = K(-0.07, -32, -30, 19, SL, SR, g(0.42, -0.10, 0.86, -30, (1.60, -0.20, 0.32)), P_FRONT)
    sl[18] = K(-0.05, -45, -36, 12, SL, SR, g(0.46, -0.12, 0.90, -36, (1.20, -0.40, 0.32)), P_FRONT)            # поза 7
    sl[20] = K(-0.03, -52, -34, 9, SL, SR, g(0.46, -0.14, 0.92, -34, (1.00, -0.50, 0.32)), P_FRONT)

    # ---- Wait1/Wait2: вис между нажатиями (маска верха; кисти почти стоят, лёгкое покачивание; 12 = 0) ------------------
    def wait(k0, sgn):
        out = {0: k0, 12: k0}
        for f, ph in ((3, 1.0), (6, 0.0), (9, -1.0)):
            q = lerp_key(k0, k0, 0.0); q["hint"] = {}
            q["cyaw"] = k0["cyaw"] + 3.0 * ph * sgn; q["lean"] = k0["lean"] + (0.8 if f == 6 else 0.0)
            q["hand"] = {s: (v[0] + 0.012 * ph, v[1] + 0.010 * ph * sgn, v[2] - (0.012 if f == 6 else 0.0)) for s, v in k0["hand"].items()}
            out[f] = q
        return out
    w1 = wait(s1[12], 1.0)
    w2 = wait(s2[11], -1.0)

    # ---- Stow: рукоять махом через правое плечо на крепление спины (3 = stowHandoff, поза снятия), кисти в стойку (4–7) ----
    st = {0: sl[20]}
    st[1] = K(-0.03, -55, -46, 8, SL, SR, g(0.42, -0.10, 1.10, -46, (1.00, -0.70, 0.60)), P_FRONT)
    st[2] = K(-0.03, -58, -60, 8, SL, SR, g(0.32, -0.14, 1.22, -60, (0.60, -1.40, 1.60)), P_FRONT)
    st[3] = K(-0.03, -62, -72, 8, SL, SR, free(*DRAW2, -72), P_DRAW, gL=1.0, gR=0.4, handle=False)             # на спину
    st[4] = K(-0.02, -58, -55, 7, SL, SR, free(*DRAW1, -55), P_DRAW1, gL=0.6, gR=0.1, handle=False)
    # кисти к стойке ключами с локтями стойки (без перескока решения между позой снятия и стойкой)
    lf0, rf0 = to_chest(SF["pos"]["Left"], -42), to_chest(SF["pos"]["Right"], -42)
    lx0, rx0 = to_chest_dir(SF["ax"]["Left"], -42), to_chest_dir(SF["ax"]["Right"], -42)
    pst = (to_chest_dir(SF["pole"]["Left"], -42, root=True), to_chest_dir(SF["pole"]["Right"], -42, root=True))
    mix = lambda a, b, t: tuple(x + (y - x) * t for x, y in zip(a, b))
    st[5] = K(-0.015, -55, -48, 7, SL, SR, free(mix(DRAW1[0], lf0, .55), mix(DRAW1[1], rf0, .55), mix(DRAW1[2], lx0, .6),
                                                mix(DRAW1[3], rx0, .5), -48),
              (mix(P_DRAW1[0], pst[0], .5), mix(P_DRAW1[1], pst[1], .5)), gL=0.3, gR=0.05, handle=False)
    st[6] = K(-0.005, -53, -42, 6.7, SL, SR, free(mix(DRAW1[0], lf0, .88), mix(DRAW1[1], rf0, .88), lx0, rx0, -42),
              pst, gL=0.1, gR=0.0, handle=False)
    st[7] = S
    return {SFX + "Swing1": s1, SFX + "Swing2": s2, SFX + "Slam": sl, SFX + "Wait1": w1, SFX + "Wait2": w2, SFX + "Stow": st}
