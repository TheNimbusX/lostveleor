def body_at(f):
    """Параметры тела в кадре f (целый — ключ; дробный — монотонная кубика по ключам, как wk_sample)."""
    fr = sorted(KEYS)
    if f in KEYS: k = KEYS[f]
    else:
        k = tuple(pchip([(x, KEYS[x][i]) for x in fr], f) for i in range(5)) + (
            tuple(pchip([(x, KEYS[x][5][c]) for x in fr], f) for c in range(5)),)
    dz, pyaw, cyaw, lean, look, R = k
    fi = min(3.0, f)
    gL = pchip([(x, FINGERS[x][0]) for x in sorted(FINGERS)], fi)
    gR = pchip([(x, FINGERS[x][1]) for x in sorted(FINGERS)], fi)
    return dict(W=1.0, dz=dz, pyaw=pyaw, cyaw=cyaw, lean=lean, look=look, gL=gL, gR=gR,
                feet=dict(Left=SL_LOCK, Right=tuple(R)))
