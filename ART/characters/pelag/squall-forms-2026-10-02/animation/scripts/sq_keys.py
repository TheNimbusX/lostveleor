def pose(dz, pyaw, cyaw, lean, L, R, hR, hL, blade, pR=P_ELBOW_DOWN_R, pL=P_ELBOW_L, W=1.0, wB=1.0, look=0.0):
    return dict(W=W, dz=dz, pyaw=pyaw, cyaw=cyaw, lean=lean, feet=dict(Left=L, Right=R), hands=dict(Right=hR, Left=hL),
                poles=dict(Right=pR, Left=pL), blade=blade, wB=wB, look=look, sv=0.0, tv=0.0)


def plant(side, where, yaw=None, pitch=0.0, up=GROUND):
    """Лодыжка: where = FRONT/REAR; side Left → +l, Right → −l. Задняя — пятка вверх, носок наружу."""
    sgn = 1 if side == "Left" else -1
    f, l = where
    if yaw is None: yaw = (-5 * sgn if where is FRONT else 32 * sgn)
    if where is REAR and pitch == 0.0: pitch = 35.0
    return (f, sgn * l, up, yaw, pitch)


def stance(B):
    """Стойка серии сабли = кадр 0 Pelag_AN_Sabre1 (все слои с весом 0)."""
    ft = {s: (-B["ankle"][s].y, B["ankle"][s].x, B["ankle"][s].z, B["foot_yaw"][s], 0.0) for s in ("Left", "Right")}
    hd = {s: (-B["hand"][s].y, B["hand"][s].x, B["hand"][s].z) for s in ("Left", "Right")}
    bl = (-B["blade"].y, B["blade"].x, B["blade"].z)
    return pose(0.0, B["pyaw"], B["cyaw"], B["lean"], ft["Left"], ft["Right"], hd["Right"], hd["Left"], bl,
                W=0.0, wB=0.0, look=B["head"]["faceYaw"])


