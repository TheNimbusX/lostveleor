    FORE[7]["arm"] = (50, 28, 66, 0)
    # ---- обратный удар (Backhand): слева направо. Клинок идёт сзади через левый бок к цели (лист 5),
    # дальше уходит вправо — в замах прямого.
    BACK = {
        0: B0,
        1: pose(-0.07, -14, 28, 30, pushL, pushR, (0.26, 0.32, 0.97), hL_out, (-0.95, 0.30, -0.10)),
        3: pose(-0.03, -16, 26, 32, airL, airR, (0.36, 0.33, 0.96), hL_out, (-0.90, 0.40, -0.10)),
        5: pose(-0.09, -16, 22, 26, reachL, reachR, (0.48, 0.30, 0.94), hL_out, (-0.30, 0.95, 0.0)),
        6: pose(-0.125, -12, 18, 20, sL, rearR, HAND_HIT, hL_mid, HIT),                                    # лист 5: КОНТАКТ
        7: pose(-0.12, -26, -24, 21, sL, upR, (0.58, -0.30, 0.93), hL_mid, (0.30, -0.95, 0.0)),
        8: F0,
    }
    BACK[1]["arm"] = (55, 38, 66, 0); BACK[3]["arm"] = (50, 25, 66, 0); BACK[5]["arm"] = (40, 8, 64, 0)
    BACK[7]["arm"] = (45, 12, 66, 0)
    for k in (FORE[6], BACK[6]):
        k["hint"] = (30, -10, 64, 0); k["win"] = 20; k["win_sw"] = 15

    # Load (лист 1): из стойки в замах — левая стоит, правая шагом (кадр 1 в воздухе) встаёт в опорную точку замаха,
    # таз вниз, сабля назад-вправо.
    load = {0: S, 1: None, 2: F0}
    # Финиш: проводка сильнее (0–2, присед глубже), правая подтягивается и ставится в опорную точку стойки (2–5),
    # стойка листа 6 — широко, клинок горизонтально перед собой (5–6), стойка серии сабли (9). Левая стоит всё время.
    hL_p6 = (0.40, 0.10, -0.08)                              # лист 6: свободная рука вытянута вперёд
    upR2 = (-0.36, -0.10, 0.22, -55, 8)                      # правая над опорной точкой стойки
